def get_text(key, lang='en', default=None):
    """Retrieve translated text string for a given key and language."""
    if not lang or lang not in LANGUAGES:
        lang = 'en'
    
    if key in TRANSLATIONS:
        entry = TRANSLATIONS[key]
        if lang in entry and entry[lang]:
            return entry[lang]
        if 'en' in entry and entry['en']:
            return entry['en']
            
    if default is not None:
        return default
        
    # Return human readable fallback from key
    return key.replace('_', ' ').capitalize()

def get_all_translations_json(lang='en'):
    """Return a dictionary of all translated strings for client-side JS consumption."""
    result = {}
    for key, val_dict in TRANSLATIONS.items():
        result[key] = val_dict.get(lang, val_dict.get('en', key))
    return json.dumps(result, ensure_ascii=False)
